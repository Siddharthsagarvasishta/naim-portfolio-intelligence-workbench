function selectedValues(filters: GlobalFilters): string[] {
  return [
    filters.product,
    filters.segment,
    filters.channel,
    filters.geography,
    filters.riskBand,
    filters.strategy,
  ].filter((value) => !value.startsWith("All "));
}

export function deriveDemoData(filters: GlobalFilters): WorkbenchData {
  const selected = selectedValues(filters);
  const populationMultiplier = selected.reduce(
    (product, value) => product * (sizeMultipliers[value] ?? 1),
    1,
  );
  const riskMultiplier = selected.reduce(
    (product, value) => product * (riskMultipliers[value] ?? 1),
    1,
  );
  const timeAdjustment =
    {
      "Dec 2025": 1,
      "Nov 2025": 0.9,
      "Oct 2025": 0.86,
      "Sep 2025": 0.84,
      "Aug 2025": 0.82,
      "Jul 2025": 0.81,
    }[filters.reportingMonth] ?? 1;
  const riskMetricIds = new Set([
    "ANNUALISED_LOSS_RATE",
    "DELINQUENCY_30_RATE",
    "FRAUD_BPS",
    "MANUAL_REVIEW_RATE",
    "FALSE_POSITIVE_RATE",
    "FRICTION_RATE",
    "ATTRITION_RATE",
  ]);
  const volumeMetricIds = new Set([
    "ACTIVE_ACCOUNTS",
    "ENDING_RECEIVABLES",
    "TRANSACTION_VALUE",
    "EXPECTED_PROFIT",
  ]);

  const kpis = BASE_DEMO_DATA.kpis.map((metric) => {
    if (metric.value === null || metric.prior === null) return { ...metric };
    let value = metric.value;
    let prior = metric.prior;
    if (riskMetricIds.has(metric.id)) {
      value *= riskMultiplier * timeAdjustment;
      prior *= riskMultiplier * Math.max(0.8, timeAdjustment - 0.03);
    } else if (volumeMetricIds.has(metric.id)) {
      value *= populationMultiplier;
      prior *= populationMultiplier;
      if (metric.id === "EXPECTED_PROFIT") {
        value /= Math.max(0.78, Math.sqrt(riskMultiplier));
      }
    }
    const absoluteChange = value - prior;
    return {
      ...metric,
      value,
      prior,
      absoluteChange,
      relativeChange: prior === 0 ? null : absoluteChange / Math.abs(prior),
      denominator:
        selected.length > 0
          ? `${Math.max(1, Math.round(24680 * populationMultiplier)).toLocaleString()} filtered accounts`
          : metric.denominator,
    };
  });

  let filteredVintages = BASE_DEMO_DATA.vintages;
  if (filters.vintage !== "All vintages") {
    filteredVintages = filteredVintages.filter(
      (row) => row.vintage === filters.vintage,
    );
  }
  if (filters.channel !== "All channels") {
    filteredVintages = filteredVintages.filter(
      (row) => row.channel === filters.channel,
    );
  }
  const filteredStrategies =
    filters.strategy === "All strategies"
      ? BASE_DEMO_DATA.strategies
      : BASE_DEMO_DATA.strategies.filter(
          (row) =>
            row.strategy === filters.strategy ||
            (filters.strategy === "Legacy" &&
              row.strategy === "Legacy / targeted"),
        );

  return {
    ...BASE_DEMO_DATA,
    metadata: {
      ...BASE_DEMO_DATA.metadata,
      asOf:
        filters.reportingMonth === "Dec 2025"
          ? "31 Dec 2025"
          : filters.reportingMonth,
      comparisonPeriod:
        filters.comparison === "Prior year"
          ? "Same month prior year"
          : filters.comparison === "Prior quarter"
            ? "Prior quarter"
            : "Prior month",
    },
    kpis,
    vintages: filteredVintages,
    strategies: filteredStrategies,
  };
}
