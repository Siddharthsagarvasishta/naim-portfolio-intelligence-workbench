function points(values: number[], comparisonOffset = 0): TrendPoint[] {
  return values.map((value, index) => ({
    month: months[index],
    value,
    comparison:
      index > 0 ? values[index - 1] + comparisonOffset : undefined,
  }));
}

function kpi(
  id: string,
  name: string,
  shortName: string,
  value: number,
  prior: number,
  unit: KpiMetric["unit"],
  denominator: string,
  status: SignalStatus,
  formula: string,
  statisticalStatus = "Within expected variation",
): KpiMetric {
  return {
    id,
    name,
    shortName,
    value,
    prior,
    absoluteChange: value - prior,
    relativeChange: prior === 0 ? null : (value - prior) / Math.abs(prior),
    unit,
    denominator,
    status,
    statisticalStatus,
    refreshedAt: "29 Jul 2026 · 09:42 IST",
    definition: {
      formula,
      denominator,
      exclusions: "Closed, quarantined and incomplete observations",
      source: "mart_portfolio_monthly",
      version: "Metric registry v2.4",
    },
  };
}

function scenarioPoints(
  lossStart: number,
  lossStep: number,
  delinquencyStart: number,
  fraudBase: number,
  reviewBase: number,
  profitBase: number,
): ScenarioProjection[] {
  const forecastMonths = [
    "Jan 26",
    "Feb 26",
    "Mar 26",
    "Apr 26",
    "May 26",
    "Jun 26",
    "Jul 26",
    "Aug 26",
    "Sep 26",
    "Oct 26",
    "Nov 26",
    "Dec 26",
  ];
  return forecastMonths.map((month, index) => {
    const seasonality = [0, 0.03, 0.01, -0.02, -0.01, 0.02][index % 6];
    const annualisedLossRate = lossStart + lossStep * index + seasonality;
    const expectedProfit =
      profitBase - index * lossStep * 0.18 - Math.max(0, index - 7) * 0.025;
    return {
      month,
      delinquency30:
        delinquencyStart + index * lossStep * 0.22 + seasonality * 0.25,
      annualisedLossRate,
      fraudLoss: fraudBase * (1 + index * 0.012),
      reviews: Math.round(reviewBase * (1 + index * 0.009)),
      expectedProfit,
      lower: expectedProfit - 0.28 - index * 0.012,
      upper: expectedProfit + 0.3 + index * 0.01,
    };
  });
}

